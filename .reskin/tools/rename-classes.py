# Longest first so bz-btn--fill wins over bz-btn.
ORDER = sorted(MAP, key=len, reverse=True)
PATTERN = re.compile(r"(?<![\w-])(" + "|".join(re.escape(k) for k in ORDER) + r")(?![\w-])")

changed = 0
for rel in FILES:
    path = os.path.normpath(os.path.join(SRC, rel))
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    new = PATTERN.sub(lambda m: MAP[m.group(1)], text)
    if new != text:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(new)
        changed += 1
        print(f"renamed {rel}")

# Any surviving bz- class would be a hole in the map: report it.
leftovers = {}
for rel in FILES:
    path = os.path.normpath(os.path.join(SRC, rel))
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    for m in re.finditer(r"bz-[a-z0-9-]+|visually-hidden", text):
        leftovers.setdefault(m.group(0), 0)
        leftovers[m.group(0)] += 1

print(f"files changed: {changed}")
if leftovers:
    print("UNMAPPED:", leftovers)
    sys.exit(1)
print("no unmapped classes left")
